"""Soft primitive ground discs and color-independent directional chevrons.

Duplicate Glow names and duplicate Mark_N names for each two-arm chevron
are intentional: SeasonSignal iterates all descendant BaseParts by name.
No geometry is generated by gameplay code.
"""
from pathlib import Path
import importlib.util
import math
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'client-assets/Season'
IDENTITY=(1,0,0,0,1,0,0,0,1)
# Cylinder long axis is X. Rotate Z by 90 degrees: cylinder becomes flat in XZ.
FLAT=(0,-1,0,1,0,0,0,0,1)

def scalar(p,tag,name,value):
    ET.SubElement(p,tag,{'name':name}).text=str(value)

def frame(p,pos,rot,optional=False):
    if optional:
        n=ET.SubElement(ET.SubElement(p,'OptionalCoordinateFrame',{'name':'WorldPivotData'}),'CFrame')
    else:
        n=ET.SubElement(p,'CoordinateFrame',{'name':'CFrame'})
    for k,v in zip('XYZ',pos):ET.SubElement(n,k).text=f'{v:.8f}'
    for j,v in enumerate(rot):ET.SubElement(n,f'R{j//3}{j%3}').text=f'{v:.8f}'

def model(parent,name,ref):
    m=ET.SubElement(parent,'Item',{'class':'Model','referent':ref})
    p=ET.SubElement(m,'Properties');scalar(p,'string','Name',name);frame(p,(0,0,0),IDENTITY,True)
    return m

def part(parent,name,ref,size,pos,rot,color,transparency,shape=1):
    i=ET.SubElement(parent,'Item',{'class':'Part','referent':ref});p=ET.SubElement(i,'Properties')
    scalar(p,'string','Name',name)
    n=ET.SubElement(p,'Vector3',{'name':'Size'})
    for k,v in zip('XYZ',size):ET.SubElement(n,k).text=f'{v:.8f}'
    frame(p,pos,rot)
    n=ET.SubElement(p,'Color3',{'name':'Color'})
    for k,v in zip('RGB',color):ET.SubElement(n,k).text=f'{v/255:.8f}'
    scalar(p,'token','Material',272);scalar(p,'token','Shape',shape)
    scalar(p,'float','Transparency',transparency)
    for name,value in [('Anchored','true'),('CanCollide','false'),('CanQuery','false'),('CanTouch','false'),('CastShadow','false')]:scalar(p,'bool',name,value)

def make(kind,checker):
    name='SeasonGlow_'+kind
    root=ET.Element('roblox',{'version':'4'});ET.SubElement(root,'Meta',{'name':'ExplicitAutoJoints'}).text='true'
    m=model(root,name,'ROOT')
    color=(70,183,135) if kind=='Good' else (211,104,92)
    highlight=(184,230,204) if kind=='Good' else (244,188,167)
    # Separate Y planes avoid coplanar flicker; additive compositing softens
    # the outer edge with gradually smaller discs, no outlined Ring geometry.
    for j,(r,y,alpha) in enumerate([(1,.004,.70),(.79,.012,.67),(.57,.020,.62)]):
        part(m,'Glow',f'GLOW{j}',(.006,2*r,2*r),(0,y,0),FLAT,color,alpha,2)
    sign=1 if kind=='Good' else -1
    for mark,z in enumerate((.43,.08,-.27),1):
        chevron=model(m,f'Mark_{mark}',f'MARKMODEL{mark}')
        for arm,side in enumerate((-1,1)):
            angle=math.atan2(side*.1,sign*.13)
            c,s=math.cos(angle),math.sin(angle)
            rot=(c,0,s,0,1,0,-s,0,c)
            part(chevron,f'Mark_{mark}',f'MARK{mark}ARM{arm}',(.025,.008,math.hypot(.1,.13)),
                (side*.05,.032,z),rot,highlight,.55)
    ET.indent(root,space='  ');path=OUT/f'{name}.rbxmx'
    ET.ElementTree(root).write(path,encoding='utf-8',xml_declaration=True)
    assert not checker.inspect(path,'client/Season'),checker.inspect(path,'client/Season')
    # Validate actual oriented extents, physics, hierarchy and identifiers.
    refs=[i.get('referent') for i in m.iter('Item')];assert len(refs)==len(set(refs))
    parts=[i for i in m.iter('Item')if i.get('class')=='Part'];assert len(parts)==9
    assert m.find("Properties/Ref[@name='PrimaryPart']") is None
    ymax=0
    for item in parts:
        p=item.find('Properties');cf=p.find("CoordinateFrame[@name='CFrame']");sz=p.find("Vector3[@name='Size']")
        dims=[float(sz.find(k).text)for k in 'XYZ']
        top=float(cf.find('Y').text)+sum(abs(float(cf.find(f'R1{j}').text))*dims[j]/2 for j in range(3))
        ymax=max(ymax,top)
        assert .55<=float(p.find("float[@name='Transparency']").text)<=.70
        assert p.find("token[@name='Material']").text=='272'
        for key in ('CanCollide','CanQuery','CanTouch'):assert p.find(f"bool[@name='{key}']").text=='false'
        if p.find("token[@name='Shape']").text=='2':assert dims[1]==dims[2]
    assert ymax<=.05
    print(name,'9 BaseParts; flat Y upper',ymax,'max radius 1; Good -Z / Bad +Z chevrons')

def main():
    spec=importlib.util.spec_from_file_location('checker',ROOT/'scripts/check-assets.py');c=importlib.util.module_from_spec(spec);spec.loader.exec_module(c)
    OUT.mkdir(parents=True,exist_ok=True)
    for kind in ('Good','Bad'):make(kind,c)

if __name__=='__main__':main()
